// Sistema de Rangos Juveniles por XP
export const PLAYER_RANKS = [
  { minXp: 0, title: 'Recluta de Luz', badge: '🌱', color: 'text-zinc-300' },
  { minXp: 400, title: 'Explorador Activo', badge: '⚡', color: 'text-sky-400' },
  { minXp: 1200, title: 'Portador del Fuego', badge: '🔥', color: 'text-amber-400' },
  { minXp: 2500, title: 'Guardián del Código', badge: '🛡️', color: 'text-violet-400' },
  { minXp: 4500, title: 'Leyenda ICAF', badge: '👑', color: 'text-emerald-400' },
];

export function getPlayerRank(xp = 0) {
  let current = PLAYER_RANKS[0];
  let next = PLAYER_RANKS[1] || null;

  for (let i = 0; i < PLAYER_RANKS.length; i++) {
    if (xp >= PLAYER_RANKS[i].minXp) {
      current = PLAYER_RANKS[i];
      next = PLAYER_RANKS[i + 1] || null;
    }
  }

  const progressToNext = next
    ? Math.min(100, Math.round(((xp - current.minXp) / (next.minXp - current.minXp)) * 100))
    : 100;

  return { current, next, progressToNext };
}
