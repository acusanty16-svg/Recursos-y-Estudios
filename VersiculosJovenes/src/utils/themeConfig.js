// Limpia signos de puntuación para comparar palabras clave con tokens del texto
export const cleanWord = (word = '') =>
  word
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9ñ]/gi, '');
